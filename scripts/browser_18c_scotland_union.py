#!/usr/bin/env python3
"""Seventh Scotland long-form source-backed interactive map in real desktop Chrome."""
from pathlib import Path
from selenium import webdriver
from selenium.webdriver.chrome.options import Options
from selenium.webdriver.common.by import By
from selenium.webdriver.support.ui import WebDriverWait
root=Path(__file__).resolve().parents[1]; shots=root/'browser-smoke-results';shots.mkdir(exist_ok=True)
opt=Options()
for arg in ('--headless=new','--disable-gpu','--no-sandbox','--disable-dev-shm-usage','--window-size=1780,1020'):opt.add_argument(arg)
driver=webdriver.Chrome(options=opt);wait=WebDriverWait(driver,60)
def js(s,*a):return driver.execute_script(s,*a)
def at(y):return js("return document.querySelector('#bigYear')?.textContent===String(arguments[0])",y)
def year(y):js("window.atlasStoryBridge.setYear(arguments[0])",y);wait.until(lambda d:at(y))
story='E18-T31-T32-SCOTLAND-UNION-CULLODEN-1700-1799'
try:
 driver.get('http://127.0.0.1:8765/?review18c=1&year=1746')
 wait.until(lambda d:at(1746))
 wait.until(lambda d:js("return !!window.atlasStoryBridge?.eventById?.('E18C-SCT-1746-CULLODEN')"))
 assert js("return window.atlasStoryBridge.eventById('E18C-SCT-1707-GREAT-BRITAIN-UNION').lat===null")
 assert js("return window.atlasStoryBridge.eventById('E18C-SCT-1700-DARIEN-SURRENDER').lat!==null")
 assert js("return window.atlasStoryBridge.eventById('E18C-SCT-1792-YEAR-OF-SHEEP').lat===null")
 original_zoom=js("return window.atlasReadViewport().zoom")
 card='#eventList [data-eid="E18C-SCT-1746-CULLODEN"]'
 wait.until(lambda d:js("return !!document.querySelector(arguments[0])",card))
 driver.find_element(By.CSS_SELECTOR,card).click()
 wait.until(lambda d:js("return !!document.querySelector('#dossierBody [data-story-open=\"E18-T31-T32-SCOTLAND-UNION-CULLODEN-1700-1799\"]')"))
 driver.find_element(By.CSS_SELECTOR,'#dossierBody [data-story-open="E18-T31-T32-SCOTLAND-UNION-CULLODEN-1700-1799"]').click()
 wait.until(lambda d:js("return document.querySelector('.major-story-article')?.dataset.storyId===arguments[0]",story))
 wait.until(lambda d:js("return document.querySelectorAll('.major-story-article .story-event-link').length===23"))
 assert js("return document.querySelectorAll('.major-story-article .story-section').length===19")
 driver.save_screenshot(str(shots/'18c-scotland-1746-culloden-longstory.png'))
 driver.find_element(By.CSS_SELECTOR,'.story-event-link[data-story-event="E18C-SCT-1700-DARIEN-SURRENDER"]').click()
 wait.until(lambda d:at(1700))
 wait.until(lambda d:js("return window.atlasStoryBridge.activeFocusId()==='E18C-SCT-1700-DARIEN-SURRENDER'"))
 wait.until(lambda d:js("""const c=window.atlasReadViewport().center;return Math.abs(c.lat-8.916667)<0.6&&Math.abs(c.lng+77.7)<0.6"""))
 assert original_zoom==js("return window.atlasReadViewport().zoom")
 driver.save_screenshot(str(shots/'18c-scotland-1700-scots-darien-garrison-ended.png'))
 driver.find_element(By.CSS_SELECTOR,'.story-event-link[data-story-event="E18C-SCT-1719-GLENSHIEL"]').click()
 wait.until(lambda d:at(1719))
 wait.until(lambda d:js("return window.atlasStoryBridge.activeFocusId()==='E18C-SCT-1719-GLENSHIEL'"))
 wait.until(lambda d:js("""const c=window.atlasReadViewport().center;return Math.abs(c.lat-57.170256)<0.6&&Math.abs(c.lng+5.316893)<0.6"""))
 driver.save_screenshot(str(shots/'18c-scotland-1719-HES-glenshiel.png'))
 driver.find_element(By.CSS_SELECTOR,'.story-event-link[data-story-event="E18C-SCT-1745-GLENFINNAN-STANDARD"]').click()
 wait.until(lambda d:at(1745))
 wait.until(lambda d:js("return window.atlasStoryBridge.activeFocusId()==='E18C-SCT-1745-GLENFINNAN-STANDARD'"))
 wait.until(lambda d:js("""const c=window.atlasReadViewport().center;return Math.abs(c.lat-56.869196)<0.6&&Math.abs(c.lng+5.437078)<0.6"""))
 driver.find_element(By.CSS_SELECTOR,'.story-event-link[data-story-event="E18C-SCT-1707-GREAT-BRITAIN-UNION"]').click()
 wait.until(lambda d:at(1707))
 assert js("return document.querySelector('.major-story-article')!==null")
 target=driver.find_element(By.CSS_SELECTOR,'.story-event-link[data-story-event="E18C-SCT-1747-FORFEITED-ESTATES"]')
 js("arguments[0].dispatchEvent(new MouseEvent('dblclick',{bubbles:true,cancelable:true}));",target)
 wait.until(lambda d:at(1747))
 wait.until(lambda d:js("return !!document.querySelector('#dossierBody [data-story-back]')"))
 driver.find_element(By.CSS_SELECTOR,'#dossierBody [data-story-back]').click()
 wait.until(lambda d:js("return document.querySelector('.major-story-article')?.dataset.storyId===arguments[0]",story))
 driver.find_element(By.CSS_SELECTOR,'[data-story-return]').click()
 wait.until(lambda d:at(1746))
 assert not js("return !!document.querySelector('.major-story-article')")
 year(1799);assert js("return document.querySelector('#nextYear').disabled")
 driver.get('http://127.0.0.1:8765/?year=1746')
 wait.until(lambda d:at(1699))
 assert js("return window.atlasStoryBridge.eventById('E18C-SCT-1746-CULLODEN')===null")
 driver.get('http://127.0.0.1:8765/?year=1572')
 wait.until(lambda d:at(1572))
 assert js("""return [...document.querySelectorAll('#eventList [data-eid]')].some(x=>x.dataset.eid==='1570S-E004')""")
 print('PASS Scotland 18C desktop: 23 links and 19 chapters, 1700 Darien cross-year pan, 1719 HES Glenshiel site, 1745 Glenfinnan later monument, 1707 constitutional null-site, 1747 double dossier/back, original return, ordinary mode isolation and 16C regression.')
except Exception:
 driver.save_screenshot(str(shots/'18c-scotland-browser-failure.png'))
 raise
finally:driver.quit()
