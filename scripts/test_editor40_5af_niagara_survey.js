#!/usr/bin/env node
'use strict';
const assert=require('node:assert/strict'),fs=require('node:fs'),path=require('node:path');
const read=p=>fs.readFileSync(path.join(__dirname,'..',p),'utf8');
const m=JSON.parse(read('data/eighteenth-century-editor40-5af-niagara-1790-survey.json'));
const js=read('js/eighteenth-editor40-5af-niagara-survey.js');
const html=read('index.html');
assert.equal(m.schema,'atlas-editor40-5af-source-registered-archival-raster-v1');
assert.equal(m.archive_reference,'NMC 17879');
assert.equal(m.survey_year,1790);
assert.deepEqual(m.visible_years,[1790,1790]);
assert.equal(m.source_spatial_reference,26917);
assert.equal(m.display_spatial_reference,4326);
assert.deepEqual(m.source_extent_m,[655208.7034025617,4789731.817320335,658636.5762775617,4792623.343160335]);
assert(m.source_image_service.startsWith('https://terra.library.brocku.ca/arcgis/rest/services/EarlyNiagara/'));
assert.equal(m.historical_fort_boundary_digitized,false);
assert.equal(m.historical_territorial_control_verified,false);
assert.equal(m.excluded_from_area_totals,true);
assert.equal(m.display_bbox_is_raster_request_only,true);
assert.equal(m.show_by_default,false);
assert.equal(html.split('id="showNiagara1790Survey"').length-1,1);
assert.equal(html.split('js/eighteenth-editor40-5af-niagara-survey.js').length-1,1);
assert(html.includes('id="niagara1790SurveyStatus"'));
assert(js.includes('year===sourceYear'));
assert(js.includes("url.searchParams.set('imageSR','4326')"));
assert(js.includes("url.searchParams.set('bboxSR','4326')"));
assert(js.includes('L.imageOverlay('));
assert(js.includes('new MutationObserver(render)'));
assert(js.includes('opacity:.67'));
assert(js.includes("pane='atlasEditor40Archive1790'"));
assert(!js.includes('L.polygon(')&&!js.includes('L.rectangle('));
console.log('PASS 5AF archival 1790 map: source original NMC 17879, EPSG26917 raster reprojection, date-only opt-in, no invented historical territorial polygon.');
