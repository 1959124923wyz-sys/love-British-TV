#!/usr/bin/env node
'use strict';
const assert=require('node:assert/strict'),fs=require('node:fs'),path=require('node:path');
const root=path.resolve(__dirname,'..');
const text=p=>fs.readFileSync(path.join(root,p),'utf8');
const app=text('app.js'),html=text('index.html'),css=text('css/dark-atlas-v2.css');
const data=JSON.parse(text('data/atlas-1540-1549.json'));
const garrison=JSON.parse(text('data/military-control-points-1540-1549.geojson'));
assert.ok(!app.includes('title:item.name'), 'Leaflet markers must not create a second native tooltip over the dark source tooltip');
assert.ok(!app.includes('title:c.name'), 'Landing candidate markers must not create duplicated tooltips');
assert.ok(!app.includes("title:g.items.length+'项历史记录'"), 'Aggregate marker must not show browser-native duplicate hover');
assert.ok(app.includes('.bindTooltip(hoverCard('), 'Keep the approved single styled historical tooltip');
assert.ok(app.includes('aria-label="'), 'Accessible marker labels must survive removal of native title');
assert.ok(!app.includes('function renderAnnualControlSummary()'),'Unwanted yearly military badge must be removed');
assert.ok(app.includes('function openTerritoryDossier(feature,kind=')&&app.includes('function renderContestedZones()'),'Historical area introductions must stay available');
assert.ok(app.includes('dashArray:french?'), 'Occupied strongholds should display a clear dashed uncertainty boundary on the correct map point');
assert.ok(app.includes("radius:map.getZoom()>=6?19:17"),'Occupied areas must be pixel-sized status rings, never measured land area');
assert.ok(app.includes("p.year_end_start")&&app.includes("p.year_end_stop"),'Status rings must track evidence-supported annual years');
assert.ok(!html.includes('id="controlStatus"')&&html.includes('swatch english-garrison')&&html.includes('swatch french-defence'),'Delete statistics but retain the military layer legend');
assert.ok(!css.includes('.year-control-status'),'Do not ship obsolete yearly badge layout');
assert.ok(html.includes('app.js?v=timeline-v176')&&html.includes('css/dark-atlas-v2.css?v=timeline-v176'));
assert.ok(html.includes('历史档案与文献')&&!html.includes('HISTORICAL DOSSIER'));
assert.ok(!html.includes('已发布1497—1549五个历史章节'),'Incorrect published chapter count');
const ireland=data.events.find(e=>e.id==='1540S-002');
assert.ok(ireland.name.includes('领主辖区')&&ireland.name.includes('王国')&&!/Lordship|Kingdom/.test(ireland.name));
assert.ok(ireland.date_label.includes('1541年')&&ireland.date_label.includes('1542年'));
assert.ok(data.events.every(e=>/中文/.test(e.date_label) || !/[A-Za-z]/.test(e.date_label)),'Public date badges must not contain untranslated research-English annotation');
assert.ok(data.events.every(e=>e.research_date_label || /^\d{4}年/.test(e.date_label)),'Research dates must remain recoverable');
const original=JSON.parse(text('data/atlas-1530-1539.json'));
assert.equal(original.events.length,27,'Fifth-chapter historic record must remain untouched');
assert.equal(garrison.features.length,19,'Roxburgh sourced 1547 artillery fort reference point included');
assert.ok(garrison.features.some(f=>f.properties.stable_id==='roxburgh-english-artillery-fort-1547-1550'&&f.properties.fill_authorized===false));
assert.ok(garrison.features.every(f=>f.geometry.type==='Point'),'Neither an English siege nor French defence implies surveyed polygon');
const hailes=garrison.features.find(f=>f.properties.stable_id==='hailes-english-1548-date_unknown');
assert.equal(hailes,undefined,'Hailes must not be mapped as an English year-end stronghold following the 1548 Scottish recapture');
const dundee=garrison.features.find(f=>f.properties.stable_id==='dundee-english-town-late-1547');
assert.equal(dundee.properties.year_end_start,1547);
assert.equal(dundee.properties.year_end_stop,1547);
console.log('PASS: single map hover, Chinese titles/dates, documented 1548 Hailes Scots recapture and 1547 Dundee occupation');
